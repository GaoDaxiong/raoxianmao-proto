// Records the solver's path and writes js/v6/route_U.js: checkpoints used by the in-game "stuck helper" (arrow + gentle wind carry).
global.TR = {}; const D = '/workspace/letter-game/proto/js/v6/';
for (const f of ['letters.js', 'route_U.js', 'sim.js', 'bot.js']) require(D + f);
TR.on = () => {};
TR.rescueOff = true; const S = TR.newGame('U'); TR.botReset(); 
const pts = [];
for (let f = 0; f < 300 * 60 && !S.done; f++) { const b = TR.botStep(S); TR.update(1 / 60, { x: b.x, y: 0, jd: b.j, jq: b.jq, aq: b.aq });
  pts.push([S.p.x, S.p.y, S.L.fog.filter(q => q.cleared).length, S.boss && S.boss.dead ? 1 : 0, S.p.room ? 1 : 0, S.p.inCart ? 1 : 0, S.p.ground ? 1 : 0]); }
if (!S.done) { console.error('solver did not finish'); process.exit(1); }
const out = []; let last = null, acc = 0;
for (const q of pts) { if (q[4]) continue; if (!last) { out.push(q); last = q; continue; }
  acc += Math.hypot(q[0] - last[0], q[1] - last[1]); last = q;
  if (acc >= 2 || q[2] !== out[out.length - 1][2] || q[3] !== out[out.length - 1][3]) { out.push(q); acc = 0; } }
out.push(pts[pts.length - 1]);
const r = v => Math.round(v * 10) / 10;
const txt = '// generated by /workspace/pwtest/genroute.js from the solver run — regenerate after changing the level layout\n// [x, y, fogCleared, bossDead, inCart, grounded]\n(function (root) { const TR = root.TR; TR.ROUTES = TR.ROUTES || {}; TR.ROUTES.U = ' +
  JSON.stringify(out.map(q => [r(q[0]), r(q[1]), q[2], q[3], q[5], q[6]])) + '; })(typeof window !== "undefined" ? window : globalThis);\n';
require('fs').writeFileSync(D + 'route_U.js', txt); console.log('checkpoints', out.length, 'time', S.t.toFixed(1));
